import {test, expect} from '../../support/fixtures'
import {createCompassSpace, readCompassEntry, updateCompassEntry} from './compassApi'

test('writing, conflicting edits and history restoration preserve actual content', async ({authenticatedPage: page, apiContext, userToken}) => {
	const space = await createCompassSpace(apiContext, userToken, {title: 'Long-term notes'})
	await page.goto(`/compass/spaces/${space.id}/write?kind=principle`)
	await page.getByLabel('Title', {exact: true}).fill('Original principle')
	await page.locator('.compass-desk .ProseMirror[contenteditable=true]').fill('Keep the original context and evidence.')
	const created = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith(`/compass/spaces/${space.id}/entries`))
	await page.locator('.compass-desk__save').click()
	const createdResponse = await created
	expect(createdResponse.status()).toBe(201)
	const entry = await createdResponse.json()
	await expect(page).toHaveURL(new RegExp(`/compass/entries/${entry.id}/edit$`))
	await expect(page.locator('.compass-desk__save')).toHaveAttribute('aria-disabled', 'true')
	const initial = await readCompassEntry(apiContext, userToken, entry.id)
	expect(initial.kind).toBe('principle')
	expect(initial.content).toContain('Keep the original context and evidence.')

	await page.getByLabel('Title', {exact: true}).fill('My current writing')
	await updateCompassEntry(apiContext, userToken, entry.id, {title: 'Written in another tab'})
	const conflict = page.waitForResponse(response => response.request().method() === 'PUT' && response.url().endsWith(`/compass/entries/${entry.id}`))
	await page.locator('.compass-desk__save').click()
	expect((await conflict).status()).toBe(409)
	await expect(page.getByLabel('Title', {exact: true})).toHaveValue('My current writing')
	await page.getByRole('button', {name: 'Keep my version', exact: true}).click()
	const saved = page.waitForResponse(response => response.request().method() === 'PUT' && response.url().endsWith(`/compass/entries/${entry.id}`) && response.status() === 200)
	await page.locator('.compass-desk__save').click()
	await saved
	await expect(page.locator('.compass-desk__save')).toHaveAttribute('aria-disabled', 'true')
	expect((await readCompassEntry(apiContext, userToken, entry.id)).title).toBe('My current writing')

	await page.goto(`/compass/entries/${entry.id}/history?revision=1`)
	await page.getByRole('button', {name: 'Restore this version', exact: true}).click()
	const dialog = page.getByRole('dialog', {name: 'Restore version 1?'})
	const restored = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith(`/compass/entries/${entry.id}/revisions/1/restore`))
	await dialog.getByRole('button', {name: 'Restore version 1', exact: true}).click()
	expect((await restored).status()).toBe(200)
	await expect(dialog).toBeHidden()
	const after = await readCompassEntry(apiContext, userToken, entry.id)
	expect(after.title).toBe('Original principle')
	expect(after.content).toBe(initial.content)
	expect(after.revision).toBe(4)
})

test('a new draft survives leaving, reopening and a failed offline save', async ({authenticatedPage: page, apiContext, userToken}) => {
	const space = await createCompassSpace(apiContext, userToken, {title: 'Draft safety'})
	await page.goto(`/compass/spaces/${space.id}/write`)
	await page.getByLabel('Title', {exact: true}).fill('Do not lose this draft')
	await page.locator('.compass-desk .ProseMirror[contenteditable=true]').fill('Words written before the network disappeared.')
	await page.locator('.compass-desk__back').click()
	const dialog = page.getByRole('dialog', {name: 'Leave without saving?'})
	await dialog.getByRole('button', {name: 'Leave and keep the draft', exact: true}).click()
	await expect(page).toHaveURL(new RegExp(`/compass/spaces/${space.id}$`))
	await page.goto(`/compass/spaces/${space.id}/write`)
	await expect(page.getByLabel('Title', {exact: true})).toHaveValue('Do not lose this draft')
	await expect(page.locator('.compass-desk .ProseMirror')).toContainText('Words written before the network disappeared.')
	await page.context().setOffline(true)
	await page.locator('.compass-desk__save').click()
	await expect(page.locator('.compass-desk')).toContainText(/offline|connection|network/i)
	await expect(page.getByLabel('Title', {exact: true})).toHaveValue('Do not lose this draft')
	await page.context().setOffline(false)
	const created = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith(`/compass/spaces/${space.id}/entries`))
	await page.locator('.compass-desk__save').click()
	const response = await created
	expect(response.status()).toBe(201)
	const entry = await response.json()
	await expect(page).toHaveURL(new RegExp(`/compass/entries/${entry.id}/edit$`))
	const saved = await readCompassEntry(apiContext, userToken, entry.id)
	expect(saved.content).toContain('Words written before the network disappeared.')
	expect(saved.title).toBe('Do not lose this draft')
})
